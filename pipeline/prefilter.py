import re

_KEYWORD_PATTERN = re.compile(
    r"(?i)\b("
    r"бензин\w*|азс|заправ\w*|очеред\w*|колонк\w*|табло\w*"
    # \w* обязателен и тут (как у всех остальных веток) — без него "95й"/
    # "98е" (без дефиса) не матчили вообще: после "95" сразу шло "й" без
    # границы слова. "92-й" случайно работал — дефис сам давал границу.
    # Реальный баг, найден на живом сообщении 2026-08-10.
    r"|9[258]\w*|100\w*"
    r"|дт|дизел\w*|солярк\w*"
    r"|лукойл\w*|роснефт\w*|рн|газпром\w*|гпн|татнефт\w*|тн|опти\w*"
    # "вилга" — голое исключение: там всего одна АЗС (Лукойл), в реальном
    # чате люди зовут её просто "Вилга" без бренда (подтверждено 2026-08-10).
    r"|вилг\w*"
    r")\b"
)


def is_on_topic(text: str) -> bool:
    if not text:
        return False
    # Чат целиком тематический — любой вопрос в нём с высокой вероятностью
    # по делу, даже если сам вопрос не содержит ключевых слов темы (например,
    # короткое уточнение в духе "у суоярвского или другая?").
    return bool(_KEYWORD_PATTERN.search(text)) or "?" in text
