import hashlib

from config import AUTHOR_HASH_SECRET

# blake2b принимает ключ не длиннее 64 байт, а токен сообщества длиннее —
# сворачиваем его в 32 байта заранее.
_KEY = hashlib.sha256(AUTHOR_HASH_SECRET.encode("utf-8")).digest()


def author_fingerprint(author_id: int) -> str:
    """Устойчивый отпечаток автора вместо его VK-идентификатора (решение Р7).

    «Тот же автор» остаётся различим, конкретный человек — нет. Ключ
    локальный, поэтому по одному отпечатку восстановить id нельзя, а перебор
    по всем id сообщества без ключа не поможет.

    Само поле сейчас не читает ни один запрос: раньше в четырёх таблицах
    бессрочно лежали числовые id 87 реальных людей (находка F4) без
    единого потребителя."""
    return hashlib.blake2b(str(author_id).encode("utf-8"), key=_KEY, digest_size=8).hexdigest()
